import type { Clock, FileStorage } from '../../application/ports';

/**
 * Supabase Storage over its REST API with plain fetch and the service key (server side only).
 * The bucket is private: the browser only ever receives short-lived signed URLs.
 * The service key is sent in headers and never logged or embedded in an error message.
 *
 * Limits of the signed upload URL: Supabase fixes its validity (2 hours) and cannot cap the size
 * per URL. Size and mime are enforced by the bucket (5 MiB, allow list) and re-checked by the use
 * case through `head` before an attachment is marked ready. `expiresAt` reports the TTL the API
 * promises to the client, which is never longer than the real token lifetime.
 */

export interface SupabaseStorageConfig {
  /** Project URL, for example https://<ref>.supabase.co */
  url: string;
  serviceKey: string;
  bucket?: string;
  fetch?: typeof fetch;
  clock?: Clock;
  timeoutMs?: number;
}

/** Signed upload tokens issued by Supabase live 2 hours. */
const SUPABASE_UPLOAD_URL_LIFETIME_SECONDS = 7200;

export class StorageError extends Error {
  constructor(
    message: string,
    readonly status: number,
  ) {
    super(message);
    this.name = 'StorageError';
  }
}

/** Backslash or ASCII control characters (code points below 0x20 and DEL). */
function hasUnsafeChar(segment: string): boolean {
  for (let i = 0; i < segment.length; i++) {
    const c = segment.charCodeAt(i);
    if (c < 0x20 || c === 0x7f || c === 0x5c) return true;
  }
  return false;
}

/** Object paths are generated by the server; still, refuse anything that could escape the bucket. */
export function encodeObjectPath(path: string): string {
  const segments = path.split('/');
  if (
    path.length === 0 ||
    path.length > 512 ||
    segments.some((s) => s === '' || s === '.' || s === '..' || hasUnsafeChar(s))
  ) {
    throw new StorageError('Invalid storage path', 400);
  }
  return segments.map(encodeURIComponent).join('/');
}

export class SupabaseFileStorage implements FileStorage {
  private readonly base: string;
  private readonly bucket: string;
  private readonly fetchFn: typeof fetch;
  private readonly clock: Clock;
  private readonly timeoutMs: number;

  constructor(private readonly config: SupabaseStorageConfig) {
    const url = new URL(config.url);
    if (url.protocol !== 'https:' && url.hostname !== 'localhost' && url.hostname !== '127.0.0.1') {
      throw new Error('Supabase URL must use https');
    }
    this.base = `${url.origin}/storage/v1`;
    this.bucket = encodeURIComponent(config.bucket ?? 'invoices');
    this.fetchFn = config.fetch ?? fetch;
    this.clock = config.clock ?? { now: () => new Date() };
    this.timeoutMs = config.timeoutMs ?? 15_000;
  }

  async createUploadUrl(
    path: string,
    _mime: string,
    _maxBytes: number,
    ttlSeconds: number,
  ): Promise<{ url: string; expiresAt: Date }> {
    const res = await this.request(
      'POST',
      `/object/upload/sign/${this.bucket}/${encodeObjectPath(path)}`,
    );
    const body = (await res.json()) as { url?: unknown };
    if (typeof body.url !== 'string' || !body.url.startsWith('/')) {
      throw new StorageError('Unexpected signed upload response', 502);
    }
    const ttl = Math.min(ttlSeconds, SUPABASE_UPLOAD_URL_LIFETIME_SECONDS);
    return {
      url: `${this.base}${body.url}`,
      expiresAt: new Date(this.clock.now().getTime() + ttl * 1000),
    };
  }

  async createDownloadUrl(path: string, ttlSeconds: number): Promise<string> {
    const res = await this.request(
      'POST',
      `/object/sign/${this.bucket}/${encodeObjectPath(path)}`,
      {
        expiresIn: Math.max(1, Math.trunc(ttlSeconds)),
      },
    );
    const body = (await res.json()) as { signedURL?: unknown };
    if (typeof body.signedURL !== 'string' || !body.signedURL.startsWith('/')) {
      throw new StorageError('Unexpected signed download response', 502);
    }
    return `${this.base}${body.signedURL}`;
  }

  /** Size and mime from the stored object's headers; Supabase does not report a sha256. */
  async head(path: string): Promise<{ sizeBytes: number; mime: string } | null> {
    const res = await this.request(
      'HEAD',
      `/object/authenticated/${this.bucket}/${encodeObjectPath(path)}`,
      undefined,
      true,
    );
    if (res === null) return null;
    const length = res.headers.get('content-length');
    const mime = res.headers.get('content-type');
    if (length === null || !/^\d+$/.test(length) || mime === null) {
      throw new StorageError('Storage did not report size and type', 502);
    }
    return { sizeBytes: Number(length), mime: mime.split(';')[0]?.trim() ?? mime };
  }

  private async request(
    method: 'POST' | 'HEAD',
    route: string,
    json?: unknown,
    allowNotFound?: false,
  ): Promise<Response>;
  private async request(
    method: 'POST' | 'HEAD',
    route: string,
    json: unknown,
    allowNotFound: true,
  ): Promise<Response | null>;
  private async request(
    method: 'POST' | 'HEAD',
    route: string,
    json?: unknown,
    allowNotFound = false,
  ): Promise<Response | null> {
    const headers: Record<string, string> = {
      authorization: `Bearer ${this.config.serviceKey}`,
      apikey: this.config.serviceKey,
    };
    const init: RequestInit = { method, headers, signal: AbortSignal.timeout(this.timeoutMs) };
    if (json !== undefined) {
      headers['content-type'] = 'application/json';
      init.body = JSON.stringify(json);
    }
    const res = await this.fetchFn(`${this.base}${route}`, init);
    // Storage answers 400 with "not_found" for missing objects on some routes.
    if (allowNotFound && (res.status === 404 || res.status === 400)) return null;
    if (!res.ok) throw new StorageError(`Storage request failed (${res.status})`, res.status);
    return res;
  }
}
